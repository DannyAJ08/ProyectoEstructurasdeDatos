    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
        String origen = JOptionPane.showInputDialog(this, "Ubicación de origen:");
        if (origen == null || origen.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe ingresar una ubicación de origen válida.");
            return;
        }

        String destino = JOptionPane.showInputDialog(this, "Ubicación de destino:");
        if (destino == null || destino.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe ingresar una ubicación de destino válida.");
            return;
        }

        String distanciaTexto = JOptionPane.showInputDialog(this, "Distancia entre ubicaciones:");
        if (distanciaTexto == null || distanciaTexto.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe ingresar una distancia.");
            return;
        }

        int distancia;

        try {
            distancia = Integer.parseInt(distanciaTexto);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "La distancia debe ser un número válido.");
            return;
        }

        tienda.agregarArista(origen, destino, distancia);

        JOptionPane.showMessageDialog(this, "Conexión agregada correctamente.");
    }//GEN-LAST:event_jButton7ActionPerformed

