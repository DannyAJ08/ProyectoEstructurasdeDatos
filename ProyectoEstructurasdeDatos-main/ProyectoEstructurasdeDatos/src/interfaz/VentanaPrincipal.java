    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String nombreCliente = JOptionPane.showInputDialog(this, "Nombre del cliente:");

        String idCliente;

        while (true) {
            idCliente = JOptionPane.showInputDialog(this, "ID del cliente:");

            if (idCliente == null) return;

            if (tienda.buscarClienteEnCola(idCliente) != null) {
                JOptionPane.showMessageDialog(this, "Error: ya existe un cliente con ese ID");
            } else {
                break;
            }
        }

        int prioridad = Integer.parseInt(
                JOptionPane.showInputDialog(this, "Prioridad (1 Básico, 2 Afiliado, 3 Premium):")
        );

        String ubicacion = JOptionPane.showInputDialog(this, "Ubicación del cliente:");

        // agregar ubicación al grafo
        tienda.agregarVertice(ubicacion);

        // crear cliente
        Cliente cliente = new Cliente(nombreCliente, idCliente, prioridad, ubicacion);

        // llenar carrito
        boolean agregarMas = true;

        while (agregarMas) {

            String idProducto = JOptionPane.showInputDialog(this, "ID del producto:");

            NodoProducto prod = tienda.buscarProducto(idProducto);

            if (prod == null) {
                JOptionPane.showMessageDialog(this, "Producto no encontrado");
            } else {

                int cant = Integer.parseInt(
                        JOptionPane.showInputDialog(this, "Cantidad:")
                );

                // validación de stock
                if (cant > prod.getCantidad()) {
                    JOptionPane.showMessageDialog(this, "No hay suficiente stock");
                    continue;
                }

                NodoProducto copia = new NodoProducto(
                        prod.getNombre(),
                        prod.getCategoria(),
                        prod.getId(),
                        prod.getPrecio(),
                        cant,
                        prod.getListaImagenes()
                );

                cliente.getCarrito().insertarNodoFInal(
                        copia.getNombre(),
                        copia.getCategoria(),
                        copia.getId(),
                        copia.getPrecio(),
                        copia.getCantidad(),
                        copia.getListaImagenes()
                );

                JOptionPane.showMessageDialog(this, "Producto agregado al carrito");
            }

            int resp = JOptionPane.showConfirmDialog(this, "¿Agregar otro producto?");
            if (resp != JOptionPane.YES_OPTION) {
                agregarMas = false;
            }
        }

        // agregar cliente a la cola
        tienda.agregarCliente(cliente);

        JOptionPane.showMessageDialog(this, "Cliente agregado correctamente");
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        if (tienda.getColaClientes().estaVacia()) {
            JOptionPane.showMessageDialog(this, "No hay clientes en la cola");
            return;
        }

        Cliente cliente = tienda.getColaClientes().verFrente();
        
        String prioridadTexto;

        if (cliente.getPrioridad() == 1) {
            prioridadTexto = "Básico";
        } else if (cliente.getPrioridad() == 2) {
            prioridadTexto = "Afiliado";
        } else {
            prioridadTexto = "Premium";
        }

        String info = "Nombre: " + cliente.getNombre() +
                      "\nID: " + cliente.getIdCliente() +
                      "\nPrioridad: " + prioridadTexto +
                      "\nUbicación: " + cliente.getUbicacion();

        JOptionPane.showMessageDialog(this, info);
    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        Cliente clienteFrente = tienda.getColaClientes().verFrente();

        if (clienteFrente == null) {
            JOptionPane.showMessageDialog(this, "No hay clientes en la cola para atender.");
            return;
        }

        if (!tienda.hayConexionConTienda(clienteFrente.getUbicacion())) {
            JOptionPane.showMessageDialog(this, "No se puede atender al cliente porque su ubicación está desconectada del mapa.");
            return;
        }

        Cliente atendido = tienda.atenderSiguienteCliente();

        if (atendido != null) {
            ResultadoDijkstra resultado = tienda.caminoMasCorto(atendido.getUbicacion());

            if (resultado == null) {
                JOptionPane.showMessageDialog(this, "No se pudo calcular la ruta de entrega.");
                return;
            }

            String factura = tienda.generarFacturaTexto(atendido);

            String ruta =
                    "\n===== RUTA DE ENTREGA =====\n" +
                    "Origen: " + tienda.getUbicacion() + "\n" +
                    "Destino: " + atendido.getUbicacion() + "\n" +
                    "Camino más corto: " + resultado.getCamino() + "\n" +
                    "Distancia total: " + resultado.getDistanciaTotal() + " km\n";

            JOptionPane.showMessageDialog(this, factura + ruta);
        }
    }//GEN-LAST:event_jButton5ActionPerformed

