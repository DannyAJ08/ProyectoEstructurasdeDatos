    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nombre = JOptionPane.showInputDialog(this, "Nombre del libro:");
        String categoria = JOptionPane.showInputDialog(this, "Categoría:");

        String id;

        while (true) {
            id = JOptionPane.showInputDialog(this, "ID:");

            if (id == null) {
                return;
            }

            if (tienda.buscarProducto(id) != null) {
                JOptionPane.showMessageDialog(this, "Error: ya existe un producto con ese ID");
            } else {
                break;
            }
        }

        double precio = Double.parseDouble(
                JOptionPane.showInputDialog(this, "Precio:")
        );

        int cantidad = Integer.parseInt(
                JOptionPane.showInputDialog(this, "Cantidad:")
        );

        ArrayList<String> imagenes = new ArrayList<>();

        int numImg = Integer.parseInt(
                JOptionPane.showInputDialog(this, "¿Cuántas imágenes desea agregar?")
        );

        for (int i = 0; i < numImg; i++) {
            String imagen = JOptionPane.showInputDialog(this, "Imagen " + (i + 1) + ":");
            imagenes.add(imagen);
        }

        NodoProducto producto = new NodoProducto(nombre, categoria, id, precio, cantidad, imagenes);
        tienda.agregarProducto(producto);

        JOptionPane.showMessageDialog(this, "Producto agregado correctamente.");
    }//GEN-LAST:event_jButton1ActionPerformed

